def split_body(body: str, limit: int = 3500) -> list[str]:
    """Режет длинный текст на части под лимит сообщения Telegram (4096).
    Рвём по абзацам, в крайнем случае — по строкам. Нужно для фолбэка, когда
    модель не разметила ответ блоками: у больших раскладов (Кельтский крест)
    цельное полотно не влезает в одно сообщение."""
    body = body or ""
    if len(body) <= limit:
        return [body]
    parts: list[str] = []
    chunk = ""
    for para in body.split("\n\n"):
        piece = para if not chunk else chunk + "\n\n" + para
        if len(piece) <= limit:
            chunk = piece
            continue
        if chunk:
            parts.append(chunk)
            chunk = ""
        # Абзац сам длиннее лимита — режем по строкам, потом жёстко
        while len(para) > limit:
            cut = para.rfind("\n", 0, limit)
            if cut <= 0:
                cut = para.rfind(" ", 0, limit)
            if cut <= 0:
                cut = limit
                # Не рвём HTML-сущность посередине (&amp; и т.п.) — Telegram
                # на такой обрывок отвечает «can't parse entities»
                amp = para.rfind("&", max(0, cut - 12), cut)
                if amp > 0 and ";" not in para[amp:cut]:
                    cut = amp
            parts.append(para[:cut])
            para = para[cut:].lstrip()
        chunk = para
    if chunk:
        parts.append(chunk)
    return parts


def cards_list_html(drawn: list[dict], labels: list[str] | None = None) -> str:
    if len(drawn) == 1:
        c = drawn[0]
        pos = " <i>(перевёрнутая)</i>" if c["rev"] else ""
        return f"<b>{c['name']}</b>{pos}"
    lines = []
    for i, c in enumerate(drawn, 1):
        pos = " <i>(перевёрнутая)</i>" if c["rev"] else ""
        if labels and i <= len(labels):
            lines.append(f"{i}. {labels[i - 1]}: <b>{c['name']}</b>{pos}")
        else:
            lines.append(f"{i}. <b>{c['name']}</b>{pos}")
    return "\n".join(lines)


