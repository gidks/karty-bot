def readings_phrase(n: int) -> str:
    if n % 10 == 1 and n % 100 != 11:
        return f"{n} расклад"
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return f"{n} расклада"
    return f"{n} раскладов"


def times_phrase(n: int) -> str:
    if n % 10 == 1 and n % 100 != 11:
        return f"{n} раз"
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return f"{n} раза"
    return f"{n} раз"

