def cards_list_html(drawn: list[dict], labels: list[str] | None = None) -> str:
    if len(drawn) == 1:
        c = drawn[0]
        pos = " <i>(перевёрнутая)</i>" if c["rev"] else ""
        return f"<b>{c['name']}</b>{pos}"
    lines = []
    for i, c in enumerate(drawn, 1):
        pos = " <i>(перевёрнутая)</i>" if c["rev"] else ""
        if labels and i <= len(labels):
            lines.append(f"{i}. {labels[i - 1]}: <b>{c['name']}</b>{pos}")
        else:
            lines.append(f"{i}. <b>{c['name']}</b>{pos}")
    return "\n".join(lines)


def free_left_phrase(n: int) -> str:
    """«остался 1 бесплатный расклад» / «осталось 2 бесплатных расклада» и т.д."""
    if n == 1:
        return "остался 1 бесплатный расклад"
    if 2 <= n <= 4:
        return f"осталось {n} бесплатных расклада"
    return f"осталось {n} бесплатных раскладов"


def days_phrase(n: int) -> str:
    if n % 10 == 1 and n % 100 != 11:
        return f"{n} день"
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return f"{n} дня"
    return f"{n} дней"


def streak_line(streak: int, best: int) -> str:
    """Строка серии под картой дня."""
    if streak <= 1:
        return ""
    line = f"\n\n🔥 Серия: {days_phrase(streak)} подряд"
    if best > streak:
        line += f" (рекорд — {days_phrase(best)})"
    return line


