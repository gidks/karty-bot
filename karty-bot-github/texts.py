_WEEKDAYS_NOM = ["понедельник", "вторник", "среда", "четверг",
                 "пятница", "суббота", "воскресенье"]
_WEEKDAYS_ACC = ["в понедельник", "во вторник", "в среду", "в четверг",
                 "в пятницу", "в субботу", "в воскресенье"]


def topup_weekday() -> str:
    """«понедельник» — день недельного пополнения, как он настроен в .env."""
    return _WEEKDAYS_NOM[config.TOPUP_WEEKDAY % 7]


def next_topup_phrase() -> str:
    """Когда придёт следующий бесплатный расклад: «уже сегодня» / «завтра» /
    «в понедельник». Считаем по Москве и по часу начисления."""
    now = datetime.now(ZoneInfo(config.TIMEZONE))
    target = config.TOPUP_WEEKDAY % 7
    days = (target - now.weekday()) % 7
    if days == 0 and now.hour >= config.TOPUP_HOUR:
        days = 7
    if days == 0:
        return "уже сегодня"
    if days == 1:
        return "завтра"
    return _WEEKDAYS_ACC[target]


def topup_enabled() -> bool:
    return config.FREE_WEEKLY_TOPUP > 0 and config.FREE_TOPUP_CAP > 0


def topup_promise() -> str:
    """Обещание про недельное пополнение — или пусто, если оно выключено."""
    if not topup_enabled():
        return ""
    return (
        f"Без стены и мелкого шрифта: <b>{next_topup_phrase()}</b> я начислю тебе "
        f"новый бесплатный расклад — и так каждую неделю, просто приходи.\n\n"
    )


def free_note() -> str:
    """Строка про то, что остаётся бесплатным — для экрана тарифов."""
    note = "Бесплатное никуда не девается: карта дня каждое утро"
    if topup_enabled():
        note += f", и каждый {topup_weekday()} — новый бесплатный расклад"
    return note + ".\n\n"


def sub_benefits(skip: str | None = None) -> str:
    """Витрина подписки с подставленными лимитами разговора.
    skip — ключ пункта, который не нужно повторять (на экране самой фичи)."""
    return "\n".join(
        line.format(d_sub=config.DIALOGUE_MAX_SUB, d_free=config.DIALOGUE_MAX)
        for key, line in SUB_BENEFIT_LINES.items() if key != skip
    )


def price(plan_key: str) -> int:
    p = config.plan(plan_key)
    return int(p["rub"]) if p else 0


def ladder_lines(skip: tuple[str, ...] = ()) -> str:
    """Полная лестница для экрана «Тарифы». В остальных местах показываем
    ОДНО предложение под момент, а не список: четыре варианта на одном экране —
    это гарантированный ноль."""
    rows = {
        "single": f"✨ <b>1 расклад</b> — {price('single')} ₽ — когда нужен один и сейчас",
        "pack5": (f"🔮 <b>{config.PACK_READINGS} раскладов</b> — {price('pack5')} ₽ — "
                  f"по {price('pack5') // max(config.PACK_READINGS, 1)} ₽ за расклад, не сгорают"),
        "bundle_him": (f"💞 <b>«Он и я»</b> — {price('bundle_him')} ₽ — "
                       "разбор одной истории на две недели"),
        "bundle_month": (f"🌙 <b>«Месяц вперёд»</b> — {price('bundle_month')} ₽ — "
                         "карта месяца и сверка каждую неделю"),
        # Имя без слова «месяц»: рядом стоит бандл «Месяц вперёд» за 249 ₽,
        # и два «месяца» с разницей в 50 ₽ читались как тарифы одного и того
        # же — причём подписка выглядела выгоднее, то есть бандл был обречён.
        "month": (f"🖤 <b>Со мной без счёта</b> — {price('month')} ₽ — "
                  "30 дней: раскладывай сколько хочешь, и всё остальное"),
    }
    keys = [k for k in config.LADDER if k not in skip]
    if not bundles_on_sale():
        keys = [k for k in keys if not k.startswith("bundle_")]
    return "\n".join(rows[k] for k in keys if k in rows)


def bundles_on_sale() -> bool:
    return bool(config.BUNDLES_ENABLED)


def free_terms() -> str:
    """Условия бесплатного доступа — для /help."""
    terms = f"Первые {config.FREE_READINGS} расклада — бесплатно."
    if topup_enabled():
        terms += (
            f" Дальше каждый {topup_weekday()} я начисляю ещё один бесплатный "
            f"(накопить можно до {config.FREE_TOPUP_CAP})."
        )
    return terms + " Хочется больше и сразу — тарифы (кнопка «💳 Тарифы»)."


def esc(s: str | None) -> str:
    """Экранирование пользовательских строк для HTML parse mode."""
    return html.escape(s or "", quote=False)


