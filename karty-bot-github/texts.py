def collection_bar(seen: int, total: int = 78, width: int = 10) -> str:
    filled = round(width * seen / total) if total else 0
    return "▰" * filled + "▱" * (width - filled)


def balance_line(free: int, paid: int, sub_until_msk: str | None) -> str:
    parts = []
    if sub_until_msk:
        parts.append(f"подписка до {sub_until_msk}")
    total = free + paid
    if total > 0:
        parts.append(f"раскладов в запасе: {total}")
    if not parts:
        return "свободных раскладов нет"
    return ", ".join(parts)
