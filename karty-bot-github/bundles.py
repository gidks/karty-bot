def get(key: str | None) -> dict | None:
    return BUNDLES.get(key or "")


def by_plan(plan_key: str) -> dict | None:
    """Сценарий по ключу тарифа ('bundle_him' -> сценарий «Он и я»)."""
    for b in BUNDLES.values():
        if b["plan"] == plan_key:
            return b
    return None


def all_keys() -> list[str]:
    """Все сценарии в порядке объявления — витрина идёт этим же порядком."""
    return list(BUNDLES.keys())


def on_sale() -> list[str]:
    """Что продаём прямо сейчас. Выключение с витрины не ломает уже купленные:
    их шаги доигрываются планировщиком до конца."""
    return all_keys() if config.BUNDLES_ENABLED else []


def step_days(key: str) -> list[int]:
    """Дни шагов от дня покупки. Берём из .env, но только если количество
    совпадает со сценарием — иначе половина шагов осталась бы без даты
    или дата без шага. При расхождении молча работаем по умолчанию."""
    b = get(key)
    if not b:
        return []
    default = b["days_default"]
    days = config.bundle_days(getattr(config, b["days_env"], ""), default)
    return days if len(days) == len(b["steps"]) else list(default)


def schedule(key: str) -> list[tuple[int, dict]]:
    """[(день, шаг), …] — расписание бандла целиком."""
    b = get(key)
    if not b:
        return []
    return list(zip(step_days(key), b["steps"]))


def last_day(key: str) -> int:
    days = step_days(key)
    return days[-1] if days else 0


def step_at(key: str, step_no: int) -> dict | None:
    b = get(key)
    if not b or step_no < 0 or step_no >= len(b["steps"]):
        return None
    return b["steps"][step_no]


def intro_questions(key: str) -> list[dict]:
    b = get(key)
    return list(b["intro"]) if b else []


def day0_spread(key: str) -> str:
    b = get(key)
    return b["day0"]["spread"] if b else "classic"


def wants_marker(key: str) -> bool:
    b = get(key)
    return bool(b and b["day0"].get("marker"))
