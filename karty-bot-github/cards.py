REVERSED_CHANCE = 0.3  # вероятность перевёрнутой карты


def draw(n: int = 3) -> list[dict]:
    """Тянет n разных карт. Возвращает [{'id', 'name', 'rev', ...}, ...]."""
    picked = random.sample(CARDS, n)
    result = []
    for c in picked:
        result.append({**c, "rev": random.random() < REVERSED_CHANCE})
    return result


def daily_card(date_str: str) -> dict:
    """Карта дня — одна на всех, детерминирована датой (у всех пользователей одинаковая)."""
    rng = random.Random("karty-ne-vrut:" + date_str)
    return rng.choice(CARDS)


def by_id(card_id: int) -> dict | None:
    for c in CARDS:
        if c["id"] == card_id:
            return c
    return None
