# Подписи позиций карт для раскладов с фиксированными ролями
SPREAD_POSITIONS: dict[str, list[str]] = {
    "classic": ["Что происходит", "Что мешает", "Куда движется"],
    "choice": ["Вариант А", "Вариант Б", "Что учесть"],
    "feelings": ["Его чувства", "Что скрыто", "Твой ход"],
}

_WEEKDAY_NAMES = ["Понедельник", "Вторник", "Среда", "Четверг",
                  "Пятница", "Суббота", "Воскресенье"]


def spread_labels(spread: str) -> list[str] | None:
    """Подписи позиций. Для «Недели» — дни, начиная с сегодняшнего (МСК)."""
    if spread == "week":
        from datetime import datetime
        from zoneinfo import ZoneInfo

        import config
        start = datetime.now(ZoneInfo(config.TIMEZONE)).weekday()
        return [_WEEKDAY_NAMES[(start + i) % 7] for i in range(7)]
    return SPREAD_POSITIONS.get(spread)


SPREAD_RULES: dict[str, str] = {
    "classic": READING_RULES + "\n\n" + SERIAL_FORMAT_3,
    "yesno": YESNO_RULES + "\n\n" + SERIAL_FORMAT_YESNO,
    "choice": CHOICE_RULES + "\n\n" + SERIAL_FORMAT_3,
    "feelings": FEELINGS_RULES + "\n\n" + SERIAL_FORMAT_3,
    "week": WEEK_RULES + "\n" + WEEK_SERIAL_NOTE + "\n\n" + SERIAL_FORMAT_WEEK,
}

MEMORY_RULES = """Про прошлые расклады:
— Тебе могут дать список прошлых раскладов этого человека. Это фон для связности, а не материал для пересказа.
— Если новый вопрос явно продолжает старую тему — можешь один раз коротко отметить это, как подруга, которая помнит прошлый разговор («в прошлый раз мы смотрели про него — похоже, история продолжается»). Если связи нет — прошлое не упоминай вообще.
— Никаких выводов вида «карты повторяются — это знак». Память — не мистика, а внимание."""

DAILY_RULES = """Карта дня:
— Тебе дадут одну карту. Напиши 3–5 предложений в стиле короткого поста: настроение дня, о чём подумать, от чего сегодня лучше воздержаться. Живо, без пафоса и без предсказаний. Обращение на «ты», без имени. Максимум один эмодзи. Название карты в тексте не повторяй — оно будет в заголовке."""


def _cards_block(drawn: list[dict], labels: list[str] | None = None) -> str:
    lines = []
    for i, c in enumerate(drawn, 1):
        pos = "перевёрнутая" if c["rev"] else "прямая"
        meaning = c["reversed"] if c["rev"] else c["upright"]
        label = f"[{labels[i - 1]}] " if labels and i <= len(labels) else ""
        lines.append(
            f"{i}. {label}{c['name']} ({pos}). Суть: {c['essence']} Опорное значение: {meaning}")
    return "\n".join(lines)


def build_reading_messages(
    name: str, topic: str, question: str, drawn: list[dict],
    past_block: str | None = None, spread: str = "classic",
) -> list[dict]:
    system = PERSONA + "\n\n" + SPREAD_RULES.get(spread, READING_RULES)
    if past_block:
        system += "\n\n" + MEMORY_RULES
    labels = spread_labels(spread)
    q = question.strip() if question else ""
    if not q:
        q = "(не сформулирован — смотри по теме и картам, без выдумывания деталей)"
    user = (
        f"Имя: {name}\n"
        f"Тема: {topic}\n"
        f"Вопрос / ситуация: {q}\n\n"
        f"Выпавшие карты:\n{_cards_block(drawn, labels)}\n\n"
    )
    if past_block:
        user += f"Прошлые расклады этого человека:\n{past_block}\n\n"
    user += "Сделай расклад по правилам."
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def build_dialogue_messages(
    name: str,
    topic: str,
    question: str,
    drawn: list[dict],
    reading_text: str,
    history: list[dict],
) -> list[dict]:
    cards_short = ", ".join(
        f"{c['name']}{' (перевёрнутая)' if c['rev'] else ''}" for c in drawn
    )
    context = (
        f"Контекст разговора.\n"
        f"Имя: {name}\nТема: {topic}\nВопрос: {question}\n"
        f"Карты расклада: {cards_short}\n"
        f"Текст расклада, который ты уже дала:\n{reading_text[:1500]}"
    )
    system = PERSONA + "\n\n" + DIALOGUE_RULES + "\n\n" + context
    return [{"role": "system", "content": system}, *history]


def build_daily_messages(card: dict) -> list[dict]:
    system = PERSONA + "\n\n" + DAILY_RULES
    user = f"Карта дня: {card['name']}. Суть: {card['essence']} Опорное значение: {card['upright']}"
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]
