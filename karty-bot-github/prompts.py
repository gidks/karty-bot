BUNDLE_FINAL_MONTH_RULES = """Закрывающее письмо разбора «Месяц вперёд» — «Что сбылось».
— Это не расклад: карты ты сейчас не тянешь. Ты проходишь по четырём неделям месяца и честно отмечаешь, где попала, а где нет.
— Тебе дадут: её слова в первый день, карту месяца и карты четырёх недель с тем, что ты про них писала, а также её рассказы о том, как недели проходили на самом деле. Плюс повторяющаяся карта, если такая есть.
— Структура письма, абзацами: чем месяц оказался на самом деле (тема месяца — подтвердилась или нет) → короткий проход по четырём неделям: где сошлось, где мимо → что она сама изменила за месяц, а что произошло без неё → повторяющаяся карта, если есть → чем месяц заканчивается и с чем она в следующий входит.
— Про попадания говори без самолюбования, про промахи — без оправданий. «Здесь я промахнулась» сказать прямо: это письмо тем и ценно, что проверяемо.
— Не продавай следующий месяц внутри письма. Про это скажет бот отдельно.
— Объём: 220–320 слов. Абзацы, без списков и служебных маркеров. Имя — один-два раза."""


def _intro_block(answers: dict | None) -> str:
    """Ответы на вопросы при входе в бандл — как она сама описала ситуацию."""
    if not answers:
        return ""
    lines = [f"— {k}: {str(v).strip()[:300]}"
             for k, v in answers.items() if str(v or "").strip()]
    return "\n".join(lines)


def build_bundle_reading_messages(
    bundle_title: str, step_title: str | None, name: str, drawn: list[dict],
    spread: str, intro_answers: dict | None = None,
    story_block: str | None = None, marker: str | None = None,
    her_answer: str | None = None, with_marker: bool = False,
    week_card_note: str | None = None,
) -> list[dict]:
    """Расклад внутри бандла: день 0 или очередной шаг.

    with_marker — от модели дополнительно требуется блок ===МАРКЕР===
    (только день 0 у сценариев, где наблюдение имеет смысл)."""
    system = PERSONA + "\n\n" + SPREAD_RULES.get(spread, READING_RULES)
    if story_block or marker:
        system += "\n\n" + BUNDLE_CONTEXT_RULES
    if with_marker:
        system += "\n\n" + BUNDLE_MARKER_RULES

    labels = spread_labels(spread)
    user = f"Имя: {name}\nРазбор: «{bundle_title}»\n"
    if step_title:
        user += f"Шаг разбора: {step_title}\n"
    intro = _intro_block(intro_answers)
    if intro:
        user += f"\nС чего она начала (её слова в первый день):\n{intro}\n"
    if story_block:
        user += f"\nЧто уже было в этом разборе:\n{story_block}\n"
    if marker:
        user += f"\nМаркер наблюдения из прошлого раза: {marker}\n"
    if her_answer:
        user += f"\nЧто она рассказала сейчас: «{her_answer.strip()[:600]}»\n"
    elif story_block:
        user += "\nОна ничего не рассказала — разложи на том, что известно.\n"
    if week_card_note:
        user += f"\n{week_card_note}\n"
    user += f"\nВыпавшие карты:\n{_cards_block(drawn, labels)}\n\nСделай расклад по правилам."
    return [_cached_system(system), {"role": "user", "content": user}]


def build_bundle_final_messages(
    bundle_key: str, bundle_title: str, name: str, story_block: str,
    intro_answers: dict | None = None, repeat_card: str | None = None,
) -> list[dict]:
    """Закрывающее письмо бандла. Карты не тянутся: это сведение арки."""
    rules = (BUNDLE_FINAL_MONTH_RULES if bundle_key == "month"
             else BUNDLE_FINAL_HIM_RULES)
    system = PERSONA + "\n\n" + rules
    user = f"Имя: {name}\nРазбор: «{bundle_title}»\n"
    intro = _intro_block(intro_answers)
    if intro:
        user += f"\nС чего она начала:\n{intro}\n"
    user += f"\nВесь разбор по порядку:\n{story_block}\n"
    if repeat_card:
        user += (f"\nКарта, которая выпадала больше одного раза за этот разбор: "
                 f"{repeat_card}\n")
    else:
        user += ("\nПовторяющихся карт не было — про повторы тогда не пиши "
                 "вообще, не выдумывай.\n")
    user += "\nНапиши письмо по правилам."
    return [_cached_system(system), {"role": "user", "content": user}]


